RETIRED_RULES = {"데/대"}


def build() -> list[dict]:
    rows, counters = [], {}
    for rule, text, gold in ITEMS:
        counters[rule] = counters.get(rule, 0) + 1
        gold = text if gold is None else gold
        # audit은 규칙 교정(자막 모드)을 먼저 돌린 결과를 모델에게 준다. 자막 모드는
